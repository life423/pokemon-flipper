import test from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import type { AddressInfo } from "node:net";
import express from "express";
import { ProviderError } from "../../server/lib/http.ts";
import { localApi } from "../../server/lib/local-api.ts";
import { createSniperScheduler } from "../../server/sniper/scheduler.ts";
import { sniperRoutes } from "../../server/sniper/routes.ts";
import type { SniperMode } from "../../shared/sniper.ts";

test("sniper API keeps marketplaces separate and rechecks the buyer's shipping quote before arming", async t => {
    const dir = await mkdtemp(path.join(tmpdir(), "sniper-routes-"));
    t.after(() => rm(dir, { recursive: true, force: true }));
    const endTime = new Date(Date.now() + 3600000).toISOString();
    const url = "https://www.ebay.com/itm/123456789012";
    let shipping = 2.99, buyer = "test-buyer";
    const reads: SniperMode[] = [];
    let sandboxAvailable = true, providerFails = false;
    const read = async (itemId: string, mode: SniperMode) => {
        reads.push(mode);
        if (providerFails) throw new ProviderError("Private upstream account diagnostics.");
        return { itemId, url, ...(mode === "sandbox" ? { buyerConnectionId: buyer, highBidder: false } : {}), title: "Mewtwo PSA 8", checkedAt: new Date().toISOString(), endTime, minimumBid: 41, currentBid: 40, shipping };
    };
    const queue = createSniperScheduler({ file: path.join(dir, "queue.json"), sandboxBuyerId: async () => buyer,
        readQuote: read, submitSandbox: () => assert.fail("A reminder must never submit a bid") });
    const app = express();
    app.use("/api/sniper", localApi, express.json(), sniperRoutes(queue, () => { assert.ok(sandboxAvailable, "buyer reminders must be independent of the sandbox"); return { sandbox: true }; }, read, () => new AbortController().signal));
    const server = app.listen(0, "127.0.0.1");
    await once(server, "listening");
    t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
    const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api/sniper`;
    const headers = { "X-Pokemon-Flipper": "1", "Content-Type": "application/json" };
    const post = (route: string, data: object) => fetch(base + route, { method: "POST", headers, body: JSON.stringify(data) });
    const live = { url, mode: "reminder" };
    assert.equal((await fetch(base)).status, 403);
    assert.equal((await post("/preview", { url, mode: "sandbox" })).status, 400);
    assert.equal((await post("/preview", { mode: "reminder", url: url.replace("www.", "www.sandbox.") })).status, 400);
    assert.equal((await post("/preview", { url, mode: "live" })).status, 400);
    assert.equal(reads.length, 0);
    const preview = await post("/preview", live);
    assert.equal(preview.status, 200);
    const { quote } = await preview.json();
    const plan = { ...live, title: quote.title, maxBid: 45, shipping: quote.shipping, endTime: quote.endTime };
    shipping = 5;
    const changedTerms = await post("", plan);
    assert.equal(changedTerms.status, 409);
    assert.equal((await changedTerms.json()).code, "AUCTION_INPUT");
    assert.deepEqual(await queue.list(), []);
    const armed = await post("", { ...plan, shipping });
    assert.equal(armed.status, 201);
    const { job } = await armed.json();
    assert.equal(job.leadSeconds, 60);
    assert.equal((await (await fetch(base, { headers })).json()).jobs[0].status, "ARMED");
    const cancelled = await fetch(base + "/" + job.id, { headers, method: "DELETE" });
    assert.equal((await cancelled.json()).job.status, "CANCELLED");
    assert.deepEqual(reads, ["reminder", "reminder", "reminder"]);
    const sandbox = { ...plan, shipping, url: url.replace("www.", "www.sandbox."), mode: "sandbox" };
    const sandboxPreview = await (await post("/preview", sandbox)).json();
    buyer = "different-buyer";
    assert.equal((await post("", { ...sandbox, buyerConnectionId: sandboxPreview.quote.buyerConnectionId })).status, 409);
    assert.equal((await queue.list()).length, 1);
    assert.equal((await post("", { ...sandbox, buyerConnectionId: buyer })).status, 201);
    sandboxAvailable = false;
    const reminders = await (await fetch(base + "?mode=reminder", { headers })).json();
    assert.deepEqual(Object.keys(reminders), ["jobs"]);
    assert.deepEqual(reminders.jobs.map((record: { id: string }) => record.id), [job.id]);

    providerFails = true;
    const unavailable = await post("/preview", live);
    assert.equal(unavailable.status, 502);
    assert.deepEqual(await unavailable.json(), { error: "eBay could not confirm the auction details." });
});
